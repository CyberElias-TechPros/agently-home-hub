CREATE TABLE IF NOT EXISTS contractors (
    id              TEXT PRIMARY KEY,
    user_id         TEXT REFERENCES users (id) ON DELETE SET NULL,
    business_name   TEXT NOT NULL,
    description     TEXT,
    categories      TEXT NOT NULL DEFAULT '[]',
    service_areas   TEXT NOT NULL DEFAULT '[]',
    hourly_rate_amount INTEGER,
    currency        TEXT NOT NULL DEFAULT 'NGN',
    rating          REAL NOT NULL DEFAULT 0,
    review_count    INTEGER NOT NULL DEFAULT 0,
    verified        INTEGER NOT NULL DEFAULT 0,
    phone           TEXT,
    email           TEXT,
    created_at      TEXT NOT NULL DEFAULT (datetime('now')),
    updated_at      TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_contractors_verified ON contractors (verified, rating DESC);

CREATE TABLE IF NOT EXISTS vendor_bookings (
    id                  TEXT PRIMARY KEY,
    contractor_id       TEXT NOT NULL REFERENCES contractors (id) ON DELETE CASCADE,
    requested_by        TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    maintenance_request_id TEXT REFERENCES maintenance_requests (id) ON DELETE SET NULL,
    scheduled_for       TEXT,
    description         TEXT,
    status              TEXT NOT NULL DEFAULT 'requested'
                        CHECK (status IN ('requested', 'confirmed', 'in_progress',
                                          'completed', 'cancelled')),
    quoted_amount       INTEGER,
    currency            TEXT NOT NULL DEFAULT 'NGN',
    created_at          TEXT NOT NULL DEFAULT (datetime('now')),
    updated_at          TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_vendor_bookings_contractor ON vendor_bookings (contractor_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_vendor_bookings_requester ON vendor_bookings (requested_by);

CREATE TABLE IF NOT EXISTS vendor_reviews (
    id              TEXT PRIMARY KEY,
    contractor_id   TEXT NOT NULL REFERENCES contractors (id) ON DELETE CASCADE,
    reviewer_id     TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    rating          INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment         TEXT,
    created_at      TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_vendor_reviews_unique ON vendor_reviews (contractor_id, reviewer_id);
CREATE INDEX IF NOT EXISTS idx_vendor_reviews_contractor ON vendor_reviews (contractor_id);

-- ---------------------------------------------------------------------------
-- Roommate matching
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS roommate_profiles (
    id              TEXT PRIMARY KEY,
    user_id         TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    headline        TEXT,
    bio             TEXT,
    age             INTEGER,
    occupation      TEXT,
    budget_min_amount INTEGER,
    budget_max_amount INTEGER,
    preferred_city  TEXT,
    smoking         INTEGER NOT NULL DEFAULT 0,
    pets            INTEGER NOT NULL DEFAULT 0,
    night_owl       INTEGER NOT NULL DEFAULT 0,
    cleanliness     INTEGER NOT NULL DEFAULT 3 CHECK (cleanliness BETWEEN 1 AND 5),
    social_level    INTEGER NOT NULL DEFAULT 3 CHECK (social_level BETWEEN 1 AND 5),
    verified        INTEGER NOT NULL DEFAULT 0,
    created_at      TEXT NOT NULL DEFAULT (datetime('now')),
    updated_at      TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_roommate_profiles_user ON roommate_profiles (user_id);
CREATE INDEX IF NOT EXISTS idx_roommate_profiles_city ON roommate_profiles (preferred_city);

CREATE TABLE IF NOT EXISTS roommate_applications (
    id                  TEXT PRIMARY KEY,
    from_profile_id     TEXT NOT NULL REFERENCES roommate_profiles (id) ON DELETE CASCADE,
    to_profile_id       TEXT NOT NULL REFERENCES roommate_profiles (id) ON DELETE CASCADE,
    message             TEXT,
    status              TEXT NOT NULL DEFAULT 'pending'
                        CHECK (status IN ('pending', 'accepted', 'declined')),
    match_score         INTEGER,
    created_at          TEXT NOT NULL DEFAULT (datetime('now')),
    updated_at          TEXT NOT NULL DEFAULT (datetime('now')),

    CHECK (from_profile_id <> to_profile_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_roommate_applications_unique
    ON roommate_applications (from_profile_id, to_profile_id);
CREATE INDEX IF NOT EXISTS idx_roommate_applications_target ON roommate_applications (to_profile_id, status);

