-- ---------------------------------------------------------------------------
-- Agently — initial D1 schema
--
-- This file consolidates (and reconciles) the 17 legacy PostgreSQL migrations
-- that lived in `server/db/migrations`. Those migrations had three defects that
-- are fixed here:
--
--   1. Duplicate tables. `maintenance` (004) and `maintenance_requests` (007)
--      both modelled a maintenance request with different columns, ids and
--      enums. Only `maintenance_requests` (the richer model, used by the API)
--      survives.
--   2. A shadowed table. `messages` was created in 005 and then created *again*
--      in 013 with `CREATE TABLE IF NOT EXISTS`, so 013 silently no-op'd and the
--      richer messaging schema never existed. Messaging is defined once, here.
--   3. Type mismatches. 007 declared `property_id INTEGER REFERENCES
--      properties(id)` while `properties.id` is a UUID, and its seed rows used
--      integer ids that could never satisfy those foreign keys.
--
-- Conventions
--   * ids      — TEXT, generated by the application (crypto.randomUUID)
--   * money    — INTEGER minor units (kobo/cents); never floating point
--   * booleans — INTEGER 0/1
--   * times    — TEXT ISO-8601 UTC
--   * lists    — TEXT holding JSON
-- ---------------------------------------------------------------------------

PRAGMA foreign_keys = ON;

-- ---------------------------------------------------------------------------
-- Identity
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS users (
    id                      TEXT PRIMARY KEY,
    name                    TEXT NOT NULL,
    email                   TEXT NOT NULL,
    password_hash           TEXT NOT NULL,
    role                    TEXT NOT NULL DEFAULT 'tenant'
                            CHECK (role IN ('tenant', 'landlord', 'agent', 'manager', 'admin')),
    phone                   TEXT,
    avatar_url              TEXT,
    verified                INTEGER NOT NULL DEFAULT 0,
    disabled_at             TEXT,
    last_login_at           TEXT,
    failed_login_attempts   INTEGER NOT NULL DEFAULT 0,
    locked_until            TEXT,
    created_at              TEXT NOT NULL DEFAULT (datetime('now')),
    updated_at              TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email ON users (lower(email));
CREATE INDEX IF NOT EXISTS idx_users_role ON users (role);

CREATE TABLE IF NOT EXISTS refresh_tokens (
    id              TEXT PRIMARY KEY,
    user_id         TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash      TEXT NOT NULL,
    user_agent      TEXT,
    ip              TEXT,
    expires_at      TEXT NOT NULL,
    revoked_at      TEXT,
    replaced_by     TEXT,
    created_at      TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_refresh_tokens_hash ON refresh_tokens (token_hash);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_user ON refresh_tokens (user_id);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_expires ON refresh_tokens (expires_at);

CREATE TABLE IF NOT EXISTS verification_tokens (
    id          TEXT PRIMARY KEY,
    user_id     TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash  TEXT NOT NULL,
    purpose     TEXT NOT NULL CHECK (purpose IN ('email_verification', 'password_reset')),
    expires_at  TEXT NOT NULL,
    used_at     TEXT,
    created_at  TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_verification_tokens_hash ON verification_tokens (token_hash);
CREATE INDEX IF NOT EXISTS idx_verification_tokens_user ON verification_tokens (user_id, purpose);

-- ---------------------------------------------------------------------------
-- Properties
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS properties (
    id                      TEXT PRIMARY KEY,
    slug                    TEXT NOT NULL,
    title                   TEXT NOT NULL,
    description             TEXT,
    type                    TEXT NOT NULL
                            CHECK (type IN ('apartment', 'house', 'condo', 'townhouse', 'studio', 'room')),
    status                  TEXT NOT NULL DEFAULT 'available'
                            CHECK (status IN ('available', 'occupied', 'maintenance', 'unavailable', 'draft')),
    landlord_id             TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,

    price_amount            INTEGER NOT NULL,          -- minor units per month
    currency                TEXT NOT NULL DEFAULT 'NGN',
    deposit_amount          INTEGER,
    minimum_lease_months    INTEGER,

    address_line1           TEXT NOT NULL,
    address_line2           TEXT,
    city                    TEXT NOT NULL,
    state                   TEXT NOT NULL,
    zip_code                TEXT NOT NULL,
    country                 TEXT NOT NULL DEFAULT 'Nigeria',
    latitude                REAL,
    longitude               REAL,

    bedrooms                INTEGER NOT NULL DEFAULT 0,
    bathrooms               REAL NOT NULL DEFAULT 0,
    area_sqft               INTEGER,
    year_built              INTEGER,

    amenities               TEXT NOT NULL DEFAULT '[]',
    images                  TEXT NOT NULL DEFAULT '[]',
    featured                INTEGER NOT NULL DEFAULT 0,
    available_from          TEXT,

    created_at              TEXT NOT NULL DEFAULT (datetime('now')),
    updated_at              TEXT NOT NULL DEFAULT (datetime('now')),
    deleted_at              TEXT
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_properties_slug ON properties (slug);
CREATE INDEX IF NOT EXISTS idx_properties_landlord ON properties (landlord_id);
CREATE INDEX IF NOT EXISTS idx_properties_status ON properties (status) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_properties_city ON properties (city, state);
CREATE INDEX IF NOT EXISTS idx_properties_price ON properties (price_amount);
CREATE INDEX IF NOT EXISTS idx_properties_featured ON properties (featured, created_at DESC);
-- Full-text search over the fields people actually type into the search box.
CREATE INDEX IF NOT EXISTS idx_properties_search ON properties (city, state, type, status, bedrooms, price_amount);

CREATE TABLE IF NOT EXISTS saved_searches (
    id          TEXT PRIMARY KEY,
    user_id     TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name        TEXT NOT NULL,
    criteria    TEXT NOT NULL DEFAULT '{}',
    alert_enabled INTEGER NOT NULL DEFAULT 1,
    last_run_at TEXT,
    created_at  TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_saved_searches_user ON saved_searches (user_id);

-- ---------------------------------------------------------------------------
-- Bookings
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS bookings (
    id                  TEXT PRIMARY KEY,
    property_id         TEXT NOT NULL REFERENCES properties (id) ON DELETE CASCADE,
    tenant_id           TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    landlord_id         TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    start_date          TEXT NOT NULL,
    end_date            TEXT,
    message             TEXT,
    status              TEXT NOT NULL DEFAULT 'pending'
                        CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled', 'completed')),
    monthly_rent_amount INTEGER NOT NULL DEFAULT 0,
    deposit_amount      INTEGER,
    currency            TEXT NOT NULL DEFAULT 'NGN',
    decision_reason     TEXT,
    decided_at          TEXT,
    created_at          TEXT NOT NULL DEFAULT (datetime('now')),
    updated_at          TEXT NOT NULL DEFAULT (datetime('now')),

    -- A tenant may not hold two live bookings for the same property.
    CHECK (tenant_id <> landlord_id)
);

CREATE INDEX IF NOT EXISTS idx_bookings_property ON bookings (property_id);
CREATE INDEX IF NOT EXISTS idx_bookings_tenant ON bookings (tenant_id);
CREATE INDEX IF NOT EXISTS idx_bookings_landlord ON bookings (landlord_id);
CREATE INDEX IF NOT EXISTS idx_bookings_status ON bookings (status);
-- Partial unique index: at most one *active* booking per (property, tenant).
CREATE UNIQUE INDEX IF NOT EXISTS idx_bookings_active_unique
    ON bookings (property_id, tenant_id)
    WHERE status IN ('pending', 'approved');

-- ---------------------------------------------------------------------------
-- Maintenance
