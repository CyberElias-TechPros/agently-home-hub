CREATE TABLE IF NOT EXISTS leads (
    id                      TEXT PRIMARY KEY,
    agent_id                TEXT REFERENCES users (id) ON DELETE SET NULL,
    first_name              TEXT NOT NULL,
    last_name               TEXT NOT NULL,
    email                   TEXT,
    phone                   TEXT,
    company                 TEXT,
    source                  TEXT NOT NULL DEFAULT 'website',
    property_id             TEXT REFERENCES properties (id) ON DELETE SET NULL,

    budget_min_amount       INTEGER,
    budget_max_amount       INTEGER,
    preferred_locations     TEXT NOT NULL DEFAULT '[]',
    preferred_property_types TEXT NOT NULL DEFAULT '[]',
    preferred_bedrooms      INTEGER,
    preferred_bathrooms     INTEGER,
    move_in_date            TEXT,

    status                  TEXT NOT NULL DEFAULT 'new'
                            CHECK (status IN ('new', 'contacted', 'interested', 'qualified',
                                              'viewing_scheduled', 'viewing_completed',
                                              'offer_made', 'closed_won', 'closed_lost')),
    priority                TEXT NOT NULL DEFAULT 'medium'
                            CHECK (priority IN ('low', 'medium', 'high', 'urgent')),
    lead_score              INTEGER NOT NULL DEFAULT 0,
    conversion_probability  INTEGER NOT NULL DEFAULT 0,
    estimated_commission_amount INTEGER,

    notes                   TEXT,
    last_contacted_at       TEXT,
    next_follow_up_at       TEXT,
    created_at              TEXT NOT NULL DEFAULT (datetime('now')),
    updated_at              TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_leads_agent ON leads (agent_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_leads_status ON leads (status);
CREATE INDEX IF NOT EXISTS idx_leads_follow_up ON leads (next_follow_up_at);

CREATE TABLE IF NOT EXISTS showings (
    id                  TEXT PRIMARY KEY,
    lead_id             TEXT NOT NULL REFERENCES leads (id) ON DELETE CASCADE,
    property_id         TEXT NOT NULL REFERENCES properties (id) ON DELETE CASCADE,
    agent_id            TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    client_name         TEXT NOT NULL,
    client_email        TEXT,
    client_phone        TEXT,
    property_address    TEXT NOT NULL,
    scheduled_date      TEXT NOT NULL,
    scheduled_time      TEXT NOT NULL,
    duration_minutes    INTEGER NOT NULL DEFAULT 60,
    status              TEXT NOT NULL DEFAULT 'scheduled'
                        CHECK (status IN ('scheduled', 'completed', 'cancelled', 'no_show')),
    notes               TEXT,
    created_at          TEXT NOT NULL DEFAULT (datetime('now')),
    updated_at          TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_showings_agent ON showings (agent_id, scheduled_date);
CREATE INDEX IF NOT EXISTS idx_showings_lead ON showings (lead_id);

CREATE TABLE IF NOT EXISTS commissions (
    id                      TEXT PRIMARY KEY,
    agent_id                TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    lead_id                 TEXT REFERENCES leads (id) ON DELETE SET NULL,
    property_id             TEXT REFERENCES properties (id) ON DELETE SET NULL,
    deal_value_amount       INTEGER NOT NULL DEFAULT 0,
    commission_rate         REAL NOT NULL DEFAULT 0,
    commission_amount       INTEGER NOT NULL DEFAULT 0,
    currency                TEXT NOT NULL DEFAULT 'NGN',
    status                  TEXT NOT NULL DEFAULT 'pending'
                            CHECK (status IN ('pending', 'earned', 'paid', 'cancelled')),
    closing_date            TEXT,
    payment_date            TEXT,
    notes                   TEXT,
    created_at              TEXT NOT NULL DEFAULT (datetime('now')),
    updated_at              TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_commissions_agent ON commissions (agent_id, created_at DESC);

-- ---------------------------------------------------------------------------
-- Vendor marketplace
