CREATE TABLE IF NOT EXISTS maintenance_requests (
    id                  TEXT PRIMARY KEY,
    property_id         TEXT NOT NULL REFERENCES properties (id) ON DELETE CASCADE,
    tenant_id           TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    landlord_id         TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    contractor_id       TEXT REFERENCES users (id) ON DELETE SET NULL,

    title               TEXT NOT NULL,
    description         TEXT NOT NULL,
    category            TEXT NOT NULL
                        CHECK (category IN ('plumbing', 'electrical', 'hvac', 'appliance',
                                            'structural', 'pest_control', 'cleaning', 'other')),
    priority            TEXT NOT NULL DEFAULT 'medium'
                        CHECK (priority IN ('low', 'medium', 'high', 'emergency')),
    status              TEXT NOT NULL DEFAULT 'pending'
                        CHECK (status IN ('pending', 'assigned', 'in_progress',
                                          'completed', 'cancelled', 'rejected')),

    area_affected       TEXT,
    access_instructions TEXT,
    images              TEXT NOT NULL DEFAULT '[]',

    tenant_notes        TEXT,
    landlord_notes      TEXT,
    contractor_notes    TEXT,

    estimated_cost_amount INTEGER,
    actual_cost_amount    INTEGER,
    currency              TEXT NOT NULL DEFAULT 'NGN',

    assigned_at         TEXT,
    completed_at        TEXT,
    created_at          TEXT NOT NULL DEFAULT (datetime('now')),
    updated_at          TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_maintenance_property ON maintenance_requests (property_id);
CREATE INDEX IF NOT EXISTS idx_maintenance_tenant ON maintenance_requests (tenant_id);
CREATE INDEX IF NOT EXISTS idx_maintenance_landlord ON maintenance_requests (landlord_id);
CREATE INDEX IF NOT EXISTS idx_maintenance_contractor ON maintenance_requests (contractor_id);
CREATE INDEX IF NOT EXISTS idx_maintenance_status ON maintenance_requests (status);
CREATE INDEX IF NOT EXISTS idx_maintenance_priority ON maintenance_requests (priority);
CREATE INDEX IF NOT EXISTS idx_maintenance_created ON maintenance_requests (created_at DESC);

CREATE TABLE IF NOT EXISTS maintenance_history (
    id                      TEXT PRIMARY KEY,
    maintenance_request_id  TEXT NOT NULL REFERENCES maintenance_requests (id) ON DELETE CASCADE,
    action                  TEXT NOT NULL
                            CHECK (action IN ('created', 'status_changed', 'assigned',
                                              'note_added', 'cost_updated')),
    old_status              TEXT,
    new_status              TEXT,
    changed_by              TEXT REFERENCES users (id) ON DELETE SET NULL,
    notes                   TEXT,
    created_at              TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_maintenance_history_request ON maintenance_history (maintenance_request_id, created_at);

-- ---------------------------------------------------------------------------
-- Documents (metadata only — bytes live in R2)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS documents (
    id              TEXT PRIMARY KEY,
    owner_id        TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    property_id     TEXT REFERENCES properties (id) ON DELETE SET NULL,
    name            TEXT NOT NULL,
    category        TEXT NOT NULL DEFAULT 'other'
                    CHECK (category IN ('lease', 'identity', 'proof_of_income', 'insurance',
                                        'inspection', 'receipt', 'other')),
    mime_type       TEXT NOT NULL,
    size_bytes      INTEGER NOT NULL,
    storage_key     TEXT NOT NULL,
    uploaded_at     TEXT,
    created_at      TEXT NOT NULL DEFAULT (datetime('now')),
    updated_at      TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_documents_owner ON documents (owner_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_documents_property ON documents (property_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_documents_storage_key ON documents (storage_key);

-- ---------------------------------------------------------------------------
-- Messaging
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS conversations (
    id                  TEXT PRIMARY KEY,
    participant_one_id  TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    participant_two_id  TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    property_id         TEXT REFERENCES properties (id) ON DELETE SET NULL,
    last_message_at     TEXT,
    last_message_preview TEXT,
    created_at          TEXT NOT NULL DEFAULT (datetime('now')),
    updated_at          TEXT NOT NULL DEFAULT (datetime('now')),

    CHECK (participant_one_id <> participant_two_id)
);

-- One conversation per unordered pair, per property.
CREATE UNIQUE INDEX IF NOT EXISTS idx_conversations_pair
    ON conversations (MIN(participant_one_id, participant_two_id),
                      MAX(participant_one_id, participant_two_id),
                      IFNULL(property_id, ''));

CREATE INDEX IF NOT EXISTS idx_conversations_participants ON conversations (participant_one_id, participant_two_id);
CREATE INDEX IF NOT EXISTS idx_conversations_recent ON conversations (last_message_at DESC);

CREATE TABLE IF NOT EXISTS messages (
    id              TEXT PRIMARY KEY,
    conversation_id TEXT NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    sender_id       TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    content         TEXT NOT NULL,
    message_type    TEXT NOT NULL DEFAULT 'text' CHECK (message_type IN ('text', 'system')),
    read_at         TEXT,
    created_at      TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_messages_conversation ON messages (conversation_id, created_at);
CREATE INDEX IF NOT EXISTS idx_messages_unread ON messages (conversation_id, read_at) WHERE read_at IS NULL;

CREATE TABLE IF NOT EXISTS message_attachments (
    id          TEXT PRIMARY KEY,
    message_id  TEXT NOT NULL REFERENCES messages (id) ON DELETE CASCADE,
    document_id TEXT REFERENCES documents (id) ON DELETE SET NULL,
    created_at  TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_message_attachments_message ON message_attachments (message_id);

